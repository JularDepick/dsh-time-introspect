import fs from 'node:fs'
import path from 'node:path'
import { build } from 'esbuild'

const outfile = path.resolve('lib/client.js')
const result = await build({
  entryPoints: ['client/index.ts'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  external: ['react'],
  legalComments: 'none',
  logLevel: 'silent',
})

const code = result.outputFiles[0]?.text
if (code === undefined) throw new Error('time-introspect: client bundle produced no output')

const wrapped = `/* dsh-time-introspect browser half; generated by scripts/build-client.mjs. */
window.__ModuleLoader__.load({
  id: "dsh-time-introspect",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${code}
    return module.exports;
  }
});
`
fs.mkdirSync(path.dirname(outfile), { recursive: true })
fs.writeFileSync(outfile, wrapped)
console.log(`built ${path.relative(process.cwd(), outfile)} (${Buffer.byteLength(wrapped)} bytes)`)
